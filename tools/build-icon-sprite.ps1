<#
.SYNOPSIS
    Builds Khaparwada.Web/wwwroot/images/icons.svg from the Font Awesome Free icons listed in tools/icons.txt.

.DESCRIPTION
    The site uses one small SVG sprite instead of the Font Awesome icon font: about 70 icons
    (~20 KB compressed) instead of 2,600 icons (~320 KB), which matters on village mobile data.

    To add an icon:
      1. Add a line such as "solid tractor" to tools/icons.txt (names: https://fontawesome.com/search?ic=free).
      2. Run this script from the repo root:  powershell -ExecutionPolicy Bypass -File tools/build-icon-sprite.ps1
      3. Use it in a view:  <icon name="tractor" />   (brand icons: <icon brand="whatsapp" />)

    Solid icons become symbols named after the icon ("tractor"); brand icons get a "brand-" prefix.
#>
param(
    [string]$Version = '7.3.1'
)

$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$repoRoot = Split-Path -Parent $PSScriptRoot
$listPath = Join-Path $PSScriptRoot 'icons.txt'
$outPath = Join-Path $repoRoot 'Khaparwada.Web\wwwroot\images\icons.svg'
$baseUrl = "https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@$Version/svgs-full"

$entries = Get-Content -LiteralPath $listPath -Encoding UTF8 |
    ForEach-Object { $_.Trim() } |
    Where-Object { $_ -and -not $_.StartsWith('#') }

$symbols = New-Object System.Collections.Generic.List[string]
$seen = @{}

foreach ($entry in $entries) {
    $parts = $entry -split '\s+'
    if ($parts.Count -ne 2 -or ($parts[0] -ne 'solid' -and $parts[0] -ne 'brands')) {
        throw "Bad line in icons.txt: '$entry'. Expected: solid <name>  or  brands <name>"
    }

    $set, $name = $parts
    $id = if ($set -eq 'brands') { "brand-$name" } else { $name }
    if ($seen.ContainsKey($id)) { continue }
    $seen[$id] = $true

    $svg = (Invoke-WebRequest -UseBasicParsing -Uri "$baseUrl/$set/$name.svg").Content
    if ($svg -is [byte[]]) { $svg = [Text.Encoding]::UTF8.GetString($svg) }

    $viewBox = [regex]::Match($svg, 'viewBox="([^"]+)"').Groups[1].Value
    $paths = [regex]::Matches($svg, '<path[^>]*/>') | ForEach-Object { $_.Value }
    if (-not $viewBox -or -not $paths) { throw "Could not read the SVG for '$set $name'." }

    $symbols.Add("<symbol id=`"$id`" viewBox=`"$viewBox`">$($paths -join '')</symbol>")
    Write-Host "  + $id"
}

$header = "<!-- Generated by tools/build-icon-sprite.ps1 from tools/icons.txt. Do not edit by hand. -->`n" +
          "<!-- Font Awesome Free $Version by @fontawesome - https://fontawesome.com License - https://fontawesome.com/license/free (Icons: CC BY 4.0) -->`n"
$sprite = $header + '<svg xmlns="http://www.w3.org/2000/svg">' + "`n" + ($symbols -join "`n") + "`n</svg>`n"

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $outPath) | Out-Null
[IO.File]::WriteAllText($outPath, $sprite, (New-Object Text.UTF8Encoding($false)))
Write-Host "Wrote $($symbols.Count) icons to $outPath ($([Math]::Round((Get-Item $outPath).Length / 1KB, 1)) KB)"
